const SPORT_MESSAGE_KEYS: Record<string, string> = {
  Run: 'run',
  Walk: 'walk',
  Ride: 'ride',
  cycling: 'ride',
  Cycling: 'ride',
  Hike: 'hike',
  Workout: 'workout',
  Training: 'workout',
  WeightTraining: 'workout',
};

export function isRideType(type: string): boolean {
  return /^(ride|cycling)$/i.test(type);
}

/** Translate an activity type for display; falls back to the raw type. */
export function sportLabel(type: string, t: (key: string) => string): string {
  const key = SPORT_MESSAGE_KEYS[type];
  return key ? t(key) : type;
}
